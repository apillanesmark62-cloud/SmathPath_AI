/* Schools for the city the student picked come first; everything else stays
   below so the full list is always reachable. */
export function schoolsForCity(city) {
  const key = String(city || "").trim().toLowerCase();
  if (!key) return PH_SCHOOLS;

  const matches = (g) => {
    const name = g.group.toLowerCase();
    return name === key || name.startsWith(key + " (") || key.startsWith(name);
  };

  const near = PH_SCHOOLS.filter(matches);
  if (!near.length) return PH_SCHOOLS;
  return [...near, ...PH_SCHOOLS.filter((g) => !matches(g))];
}
